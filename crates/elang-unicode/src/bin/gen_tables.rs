//! Generator for `src/gc_tables.rs` and `src/nfc_tables.rs` from the pinned
//! UCD 18.0.0 files.
//!
//! Emits:
//!   - gc_tables.rs: forbidden General_Category ranges (Cc/Cf/Cs/Co/Cn).
//!   - nfc_tables.rs: Canonical_Combining_Class, full canonical decompositions,
//!     and canonical composition pairs (excluding composition exclusions and
//!     non-starter decompositions), per UAX#15.
//!
//! Inputs (hashes pinned in specs/sources/ucd-18.0.0/SOURCES.md):
//!   - extracted/DerivedGeneralCategory.txt
//!   - UnicodeData.txt
//!   - CompositionExclusions.txt
//!
//! Running against those pinned files reproduces the tables byte-for-byte.
//! Run: `cargo run -p elang-unicode --bin gen_tables`
#![allow(
    clippy::expect_used,
    clippy::panic,
    clippy::indexing_slicing,
    clippy::arithmetic_side_effects,
    clippy::missing_docs_in_private_items,
    clippy::print_stderr,
    clippy::too_many_lines
)]

use std::collections::BTreeMap;
use std::fmt::Write as _;

const DGC: &str = "specs/sources/ucd-18.0.0/DerivedGeneralCategory.txt";
const UDATA: &str = "specs/sources/ucd-18.0.0/UnicodeData.txt";
const CEXCL: &str = "specs/sources/ucd-18.0.0/CompositionExclusions.txt";
const OUT_GC: &str = "crates/elang-unicode/src/gc_tables.rs";
const OUT_NFC: &str = "crates/elang-unicode/src/nfc_tables.rs";

fn is_forbidden(gc: &str) -> bool {
    matches!(gc, "Cc" | "Cf" | "Cs" | "Co" | "Cn")
}

fn gen_gc() -> usize {
    let text = std::fs::read_to_string(DGC).expect("read DerivedGeneralCategory.txt");
    let mut ranges: Vec<(u32, u32)> = Vec::new();
    for line in text.lines() {
        let line = line.split('#').next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }
        let mut parts = line.split(';');
        let cps = parts.next().expect("cp").trim();
        let gc = parts.next().expect("gc").trim();
        if !is_forbidden(gc) {
            continue;
        }
        let (s, e) = match cps.split_once("..") {
            Some((a, b)) => (
                u32::from_str_radix(a.trim(), 16).expect("hex"),
                u32::from_str_radix(b.trim(), 16).expect("hex"),
            ),
            None => {
                let v = u32::from_str_radix(cps, 16).expect("hex");
                (v, v)
            }
        };
        ranges.push((s, e));
    }
    ranges.sort_unstable();
    let mut merged: Vec<(u32, u32)> = Vec::with_capacity(ranges.len());
    for (s, e) in ranges {
        if let Some(last) = merged.last_mut() {
            if s <= last.1 + 1 {
                if e > last.1 {
                    last.1 = e;
                }
                continue;
            }
        }
        merged.push((s, e));
    }
    let mut out = String::new();
    out.push_str(
        "// @generated by `cargo run -p elang-unicode --bin gen_tables` from the\n\
         // pinned UCD 18.0.0 DerivedGeneralCategory.txt. DO NOT EDIT BY HAND.\n\
         // Sorted, merged, inclusive ranges whose General_Category is one of\n\
         // Cc/Cf/Cs/Co/Cn (the categories ELANG forbids).\n\n",
    );
    let _ = writeln!(out, "pub const DATA_UNICODE_VERSION: &str = \"18.0.0\";\n");
    let _ = writeln!(
        out,
        "/// Inclusive code-point ranges with a forbidden General_Category."
    );
    let _ = writeln!(out, "pub static FORBIDDEN_CATEGORY_RANGES: &[(u32, u32)] = &[");
    for (s, e) in &merged {
        let _ = writeln!(out, "    (0x{s:04X}, 0x{e:04X}),");
    }
    out.push_str("];\n");
    std::fs::write(OUT_GC, &out).expect("write gc_tables.rs");
    merged.len()
}

struct UcdChar {
    ccc: u8,
    decomp: Option<Vec<u32>>, // canonical decomposition only
}

fn gen_nfc() -> (usize, usize, usize) {
    let udata = std::fs::read_to_string(UDATA).expect("read UnicodeData.txt");
    let cexcl_text = std::fs::read_to_string(CEXCL).expect("read CompositionExclusions.txt");

    let mut chars: BTreeMap<u32, UcdChar> = BTreeMap::new();
    for line in udata.lines() {
        if line.trim().is_empty() {
            continue;
        }
        let f: Vec<&str> = line.split(';').collect();
        if f.len() < 6 {
            continue;
        }
        let cp = u32::from_str_radix(f[0], 16).expect("cp");
        let ccc: u8 = f[3].parse().expect("ccc");
        let decomp_field = f[5].trim();
        let decomp = if decomp_field.is_empty() || decomp_field.starts_with('<') {
            // empty, or a <compatibility> mapping which is NOT canonical.
            None
        } else {
            let seq: Vec<u32> = decomp_field
                .split_whitespace()
                .map(|h| u32::from_str_radix(h, 16).expect("hex decomp"))
                .collect();
            Some(seq)
        };
        chars.insert(cp, UcdChar { ccc, decomp });
    }

    // Composition exclusions (explicit list from the file).
    let mut excluded: std::collections::BTreeSet<u32> = std::collections::BTreeSet::new();
    for line in cexcl_text.lines() {
        let line = line.split('#').next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }
        // Lines are single code points in this file.
        if let Ok(cp) = u32::from_str_radix(line, 16) {
            excluded.insert(cp);
        }
    }

    // Full (recursive) canonical decomposition for each char that has one.
    fn full_decomp(cp: u32, chars: &BTreeMap<u32, UcdChar>, out: &mut Vec<u32>) {
        match chars.get(&cp).and_then(|c| c.decomp.as_ref()) {
            Some(seq) => {
                for &c in seq {
                    full_decomp(c, chars, out);
                }
            }
            None => out.push(cp),
        }
    }

    let mut full: BTreeMap<u32, Vec<u32>> = BTreeMap::new();
    for (&cp, c) in &chars {
        if c.decomp.is_some() {
            let mut v = Vec::new();
            full_decomp(cp, &chars, &mut v);
            full.insert(cp, v);
        }
    }

    // CCC table: only nonzero entries (default is 0).
    let mut ccc_entries: Vec<(u32, u8)> = chars
        .iter()
        .filter(|(_, c)| c.ccc != 0)
        .map(|(&cp, c)| (cp, c.ccc))
        .collect();
    ccc_entries.sort_unstable();

    // Composition pairs: from PRIMARY canonical decompositions of length 2 that
    // are (a) not in the exclusion list, and (b) whose first element is a
    // starter (CCC 0) — "non-starter decompositions" are excluded from
    // composition per UAX#15. Singleton decompositions never compose.
    let ccc_of = |cp: u32| chars.get(&cp).map_or(0u8, |c| c.ccc);
    let mut comp_pairs: Vec<((u32, u32), u32)> = Vec::new();
    for (&cp, c) in &chars {
        let Some(seq) = c.decomp.as_ref() else { continue };
        if seq.len() != 2 {
            continue; // singletons and longer canonical decomps don't compose
        }
        if excluded.contains(&cp) {
            continue;
        }
        if ccc_of(seq[0]) != 0 {
            continue; // non-starter decomposition: excluded from composition
        }
        comp_pairs.push(((seq[0], seq[1]), cp));
    }
    comp_pairs.sort_unstable();

    // Emit nfc_tables.rs
    let mut out = String::new();
    out.push_str(
        "// @generated by `cargo run -p elang-unicode --bin gen_tables` from the\n\
         // pinned UCD 18.0.0 UnicodeData.txt + CompositionExclusions.txt.\n\
         // DO NOT EDIT BY HAND. Canonical_Combining_Class, full canonical\n\
         // decompositions, and canonical composition pairs (UAX#15).\n\n",
    );
    // CCC
    let _ = writeln!(out, "/// (code point, Canonical_Combining_Class) for ccc != 0, sorted.");
    let _ = writeln!(out, "pub static CCC: &[(u32, u8)] = &[");
    for (cp, ccc) in &ccc_entries {
        let _ = writeln!(out, "    (0x{cp:04X}, {ccc}),");
    }
    out.push_str("];\n\n");

    // Full canonical decompositions
    let _ = writeln!(
        out,
        "/// (code point, full canonical decomposition), sorted by code point."
    );
    let _ = writeln!(out, "pub static DECOMP: &[(u32, &[u32])] = &[");
    for (cp, seq) in &full {
        let items: Vec<String> = seq.iter().map(|c| format!("0x{c:04X}")).collect();
        let _ = writeln!(out, "    (0x{cp:04X}, &[{}]),", items.join(", "));
    }
    out.push_str("];\n\n");

    // Composition pairs, keyed by (starter, combining) -> composed
    let _ = writeln!(
        out,
        "/// ((starter, second), composed), sorted by the (starter, second) key."
    );
    let _ = writeln!(out, "pub static COMPOSE: &[((u32, u32), u32)] = &[");
    for ((a, b), cp) in &comp_pairs {
        let _ = writeln!(out, "    ((0x{a:04X}, 0x{b:04X}), 0x{cp:04X}),");
    }
    out.push_str("];\n");

    std::fs::write(OUT_NFC, &out).expect("write nfc_tables.rs");
    (ccc_entries.len(), full.len(), comp_pairs.len())
}

fn main() {
    let ranges = gen_gc();
    let (ccc, decomp, comp) = gen_nfc();
    eprintln!("gc_tables.rs: {ranges} forbidden ranges");
    eprintln!("nfc_tables.rs: {ccc} ccc, {decomp} decomp, {comp} compose pairs");
}

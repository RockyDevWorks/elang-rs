//! # elang-repertoire
//!
//! Pinned Unicode 18.0.0 data and the ELANG IPA Repertoire v1 allowlist (base
//! symbols, combining diacritics, spacing modifiers), with RFC 8785 JCS
//! canonicalization and pinned SHA-256 verification.
//!
//! The exact approved IPA inventory is an OPEN ARTIFACT (steering §12.1) and is
//! produced and reviewed in Phase 1 before this crate's validator is frozen.
//! Implemented in Phase 8.
